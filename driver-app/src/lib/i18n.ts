const DICTS: Record<string, Dict> = { de, en, ar };

// German is the product's default until the driver explicitly picks a language
// (first run routes through the language picker). We deliberately do NOT follow
// the device language here — otherwise an Arabic phone shows Arabic on the very
// first paint before any choice is made.
let current = "de";

/**
 * Direction is handled MANUALLY per-component via `isRTL()` (flexDirection,
 * textAlign, writingDirection, side spacing, chevrons). Native RTL is kept OFF
 * so the base layout is always LTR: this avoids double-flipping (native reversing
 * `row` on top of our manual `row-reverse`) and lets a runtime language switch
 * apply instantly through the listeners below, with no app reload.
 */
export function applyDirection(_code: string) {
  I18nManager.allowRTL(false);
  if (I18nManager.isRTL) {
    I18nManager.forceRTL(false);
  }
}

applyDirection(current);

const listeners = new Set<() => void>();

export function setLocale(code: string) {
  if (DICTS[code] && code !== current) {
    current = code;
    applyDirection(code);
    // Persist here too (not only in the picker) so the choice always survives a
    // restart, from whichever path changed it.
    SecureStore.setItemAsync("locale", code).catch(() => {});
    listeners.forEach((fn) => fn());
  }
}

export function getLocale(): string {
  return current;
}

/** Non-React subscription to language changes (e.g. to re-label notification
 *  channels/actions). Returns the unsubscribe function. */
export function onLocaleChange(fn: () => void): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

// Stable identities so useSyncExternalStore doesn't resubscribe on every render.
const subscribeLocale = (fn: () => void) => onLocaleChange(fn);
const getLocaleSnapshot = () => current;

/** Re-render a component whenever the app language changes (keeps tab labels etc. in sync). */
export function useLocale(): string {
  return useSyncExternalStore(subscribeLocale, getLocaleSnapshot);
}

/**
 * The Intl locale for dates/weekdays in the current language. Arabic keeps
 * Latin digits (product rule: money/distance/dates always render Latin digits).
 */
export function intlLocale(): string {
  if (current === "ar") return "ar-u-nu-latn";
  if (current === "en") return "en-GB";
  return "de-DE";
}

export function isRTL(): boolean {
  return current === "ar";
}

export function t(key: string, vars?: Record<string, string>): string {
  const raw = DICTS[current]?.[key] ?? DICTS.de[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? `{${name}}`);
}
